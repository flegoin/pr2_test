-- ============================================================
-- База данных "Покупка билетов в театр" (упрощённая версия)
-- Схема из 9 таблиц. Демонстрируются все виды связей:
--   * один-ко-многим (1:M)
--   * многие-ко-многим (M:M)
--   * один-к-одному   (1:1)
-- Кодировка: UTF-8. Валюта: рубли (numeric).
-- ============================================================

SET client_encoding = 'UTF8';

-- Удаление в порядке, обратном зависимостям
DROP TABLE IF EXISTS актёры_спектакли CASCADE;
DROP TABLE IF EXISTS спектакли_жанры  CASCADE;
DROP TABLE IF EXISTS показы           CASCADE;
DROP TABLE IF EXISTS места            CASCADE;
DROP TABLE IF EXISTS паспорта_залов   CASCADE;
DROP TABLE IF EXISTS актёры           CASCADE;
DROP TABLE IF EXISTS спектакли        CASCADE;
DROP TABLE IF EXISTS жанры            CASCADE;
DROP TABLE IF EXISTS залы             CASCADE;

-- ------------------------------------------------------------
-- Справочник: жанры
-- ------------------------------------------------------------
CREATE TABLE жанры (
    id        integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    название  varchar(60) NOT NULL UNIQUE
);
COMMENT ON TABLE жанры IS 'Жанры театральных постановок';

-- ------------------------------------------------------------
-- Справочник: спектакли
-- ------------------------------------------------------------
CREATE TABLE спектакли (
    id                     integer  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    название               varchar(150) NOT NULL,
    описание               text,
    длительность_минут     integer  NOT NULL CHECK (длительность_минут > 0),
    возрастное_ограничение smallint NOT NULL DEFAULT 0 CHECK (возрастное_ограничение >= 0)
);
COMMENT ON TABLE спектакли IS 'Театральные постановки';

-- ------------------------------------------------------------
-- Связь МНОГИЕ-КО-МНОГИМ: спектакли <-> жанры
-- ------------------------------------------------------------
CREATE TABLE спектакли_жанры (
    спектакль_id integer NOT NULL REFERENCES спектакли(id) ON DELETE CASCADE,
    жанр_id      integer NOT NULL REFERENCES жанры(id)     ON DELETE CASCADE,
    PRIMARY KEY (спектакль_id, жанр_id)
);
COMMENT ON TABLE спектакли_жанры IS 'Связь многие-ко-многим: спектакли <-> жанры';

-- ------------------------------------------------------------
-- Справочник: актёры
-- ------------------------------------------------------------
CREATE TABLE актёры (
    id       integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    фамилия  varchar(50) NOT NULL,
    имя      varchar(50) NOT NULL,
    отчество varchar(50),
    звание   varchar(80)
);
COMMENT ON TABLE актёры IS 'Труппа театра';

-- ------------------------------------------------------------
-- Связь МНОГИЕ-КО-МНОГИМ: актёры <-> спектакли (+ роль)
-- ------------------------------------------------------------
CREATE TABLE актёры_спектакли (
    актёр_id     integer NOT NULL REFERENCES актёры(id)     ON DELETE CASCADE,
    спектакль_id integer NOT NULL REFERENCES спектакли(id)  ON DELETE CASCADE,
    роль         varchar(80),
    PRIMARY KEY (актёр_id, спектакль_id)
);
COMMENT ON TABLE актёры_спектакли IS 'Связь многие-ко-многим: актёры <-> спектакли (с ролью)';

-- ------------------------------------------------------------
-- Справочник: залы
-- ------------------------------------------------------------
CREATE TABLE залы (
    id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    название        varchar(80) NOT NULL,
    количество_мест integer     NOT NULL CHECK (количество_мест > 0),
    этаж            smallint    NOT NULL
);
COMMENT ON TABLE залы IS 'Театральные залы';

-- ------------------------------------------------------------
-- Связь ОДИН-КО-МНОГИМ: залы -> места
-- ------------------------------------------------------------
CREATE TABLE места (
    id        integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    зал_id    integer     NOT NULL REFERENCES залы(id) ON DELETE CASCADE,
    ряд       smallint    NOT NULL CHECK (ряд > 0),
    номер     smallint    NOT NULL CHECK (номер > 0),
    категория varchar(40) NOT NULL,
    UNIQUE (зал_id, ряд, номер)
);
COMMENT ON TABLE места IS 'Места в зале (много мест на один зал)';

-- ------------------------------------------------------------
-- Связь ОДИН-КО-МНОГИМ: спектакли -> показы и залы -> показы
-- ------------------------------------------------------------
CREATE TABLE показы (
    id            integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    спектакль_id  integer       NOT NULL REFERENCES спектакли(id) ON DELETE RESTRICT,
    зал_id        integer       NOT NULL REFERENCES залы(id)      ON DELETE RESTRICT,
    дата_время    timestamp     NOT NULL,
    базовая_цена  numeric(10,2) NOT NULL CHECK (базовая_цена > 0)
);
COMMENT ON TABLE показы IS 'Расписание показов (много показов на один спектакль)';

-- ------------------------------------------------------------
-- Связь ОДИН-К-ОДНОМУ: залы <-> паспорта_залов
-- (уникальный зал_id гарантирует ровно один паспорт на зал)
-- ------------------------------------------------------------
CREATE TABLE паспорта_залов (
    id            integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    зал_id        integer      NOT NULL UNIQUE REFERENCES залы(id) ON DELETE CASCADE,
    площадь       numeric(8,2) NOT NULL CHECK (площадь > 0),
    высота_сцены  numeric(4,2) NOT NULL CHECK (высота_сцены > 0),
    год_постройки smallint     NOT NULL CHECK (год_постройки BETWEEN 1500 AND 2100)
);
COMMENT ON TABLE паспорта_залов IS 'Связь один-к-одному: зал <-> технический паспорт';
