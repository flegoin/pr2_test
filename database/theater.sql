-- ============================================================
--  Проверка: количество записей в каждой таблице
-- ============================================================
SELECT 'genre'       AS table_name, COUNT(*) AS cnt FROM genre
UNION ALL SELECT 'author',       COUNT(*) FROM author
UNION ALL SELECT 'performance',  COUNT(*) FROM performance
UNION ALL SELECT 'actor',        COUNT(*) FROM actor
UNION ALL SELECT 'role',         COUNT(*) FROM role
ORDER BY table_name;


-- ============================================================
--  Демонстрационные запросы (JOIN)
-- ============================================================

-- Все спектакли с указанием жанра и автора
SELECT p.title            AS спектакль,
       g.name             AS жанр,
       a.full_name        AS автор,
       p.premiere_date    AS премьера,
       p.duration_min     AS минут,
       p.age_limit        AS возраст
FROM performance p
JOIN genre  g ON g.genre_id  = p.genre_id
JOIN author a ON a.author_id = p.author_id
ORDER BY p.premiere_date;

-- Занятость актёров: кто в каком спектакле и какую роль играет
SELECT ac.full_name AS актёр,
       p.title      AS спектакль,
       r.role_name  AS роль,
       CASE WHEN r.is_main THEN 'главная' ELSE 'второстепенная' END AS значимость
FROM role r
JOIN actor       ac ON ac.actor_id       = r.actor_id
JOIN performance p  ON p.performance_id  = r.performance_id
ORDER BY ac.full_name;

-- Количество ролей по жанрам
SELECT g.name AS жанр, COUNT(r.role_id) AS ролей
FROM genre g
JOIN performance p ON p.genre_id = g.genre_id
JOIN role r        ON r.performance_id = p.performance_id
GROUP BY g.name
ORDER BY ролей DESC;
